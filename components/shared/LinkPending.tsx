"use client";

import { useLinkStatus } from "next/link";

/**
 * Индикатор ожидания внутри `<Link>`.
 *
 * Зачем. Отклик на клик по ссылке в каталоге раньше давал `loading.tsx`, но его
 * пришлось удалить: он заставлял Next стримить ответ, из-за чего статус
 * фиксировался ДО того, как страница успевала сказать «не найдено» или
 * «перенаправить». Несуществующий товар отдавал 200 вместо 404, а редирект
 * варианта превращался в meta refresh с секундной задержкой. Вместе со
 * скелетоном ушёл и отклик: глобальный `NavigationProgress` по собственной
 * документации обслуживает только программную навигацию и клики по `<Link>`
 * не покрывает.
 *
 * `useLinkStatus` закрывает ровно этот случай — документация Next называет его
 * подходящим, когда маршрут динамический И у него нет `loading.js`.
 *
 * Отрисовка сделана по рецепту из той же документации, а не «как проще»:
 *  - элемент отрисован ВСЕГДА и занимает место, видимость переключается
 *    `visibility`/`opacity`. Возврат `null` до клика двигал бы вёрстку в
 *    момент нажатия — документация называет это прямым анти-паттерном, а в
 *    карточке каталога длинное название от лишнего элемента получило бы
 *    перенос строки и растянуло всю строку сетки;
 *  - появление отложено на 100 мс, чтобы на быстрых переходах не мигало;
 *  - `aria-hidden`, как у остальных спиннеров проекта: это украшение, а не
 *    сообщение. Пустой живой регион скринридеры всё равно не озвучивают, зато
 *    `aria-label` попал бы в доступное имя ссылки и мусорил бы его;
 *  - анимация уважает `prefers-reduced-motion` — правило из `globals.css`.
 */
export function LinkPending(): React.ReactElement {
  const { pending } = useLinkStatus();

  return (
    <span
      aria-hidden="true"
      data-pending={pending ? "true" : undefined}
      className="link-pending-hint"
    />
  );
}
