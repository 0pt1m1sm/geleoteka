/**
 * Канонический «хозяин» среди вариантов одной детали.
 *
 * У номенклатуры бывает несколько товаров: новый и б/у экземпляры. Все они —
 * одна и та же деталь с точки зрения покупателя и поисковика, поэтому
 * индексироваться должен РОВНО ОДИН адрес, а остальные указывать на него
 * каноническим тегом. Иначе варианты конкурируют между собой за один запрос —
 * ровно та каннибализация, ради устранения которой б/у лишены собственных
 * индексируемых страниц.
 *
 * Выбор обязан быть ДЕТЕРМИНИРОВАННЫМ: канонический адрес, меняющийся от
 * запроса к запросу, хуже отсутствия канонического вовсе.
 */

export interface VariantForHost {
  slug: string;
  condition: "NEW" | "USED" | "REFURBISHED";
  isActive: boolean;
  createdAt: Date;
}

/**
 * Правило: активный НОВЫЙ товар; если его нет — самый ранний активный вариант.
 * Новый выбран хозяином, потому что он долговечен: б/у экземпляр исчезает с
 * витрины после продажи (Story 4), а новый товар пополняется.
 *
 * @returns хозяин либо null, если активных вариантов нет.
 */
export function pickVariantHost<T extends VariantForHost>(variants: readonly T[]): T | null {
  const active = variants.filter((v) => v.isActive);
  if (active.length === 0) return null;

  const byAge = [...active].sort((a, b) => {
    const t = a.createdAt.getTime() - b.createdAt.getTime();
    // При равных датах — по slug: порядок обязан быть устойчивым между
    // запросами, иначе канонический адрес «плавает».
    return t !== 0 ? t : a.slug.localeCompare(b.slug);
  });

  return byAge.find((v) => v.condition === "NEW") ?? byAge[0];
}
