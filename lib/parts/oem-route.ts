import { isLatinOem, oemKey } from "@/lib/part-reference";

/**
 * Что делать с сегментом `/parts/oem/<...>`.
 *
 * Чистая функция без БД: правило адреса решается до всякого запроса, и его
 * можно проверить тестом целиком.
 */
export type OemRouteDecision =
  | { kind: "canonical"; oem: string }
  | { kind: "redirect"; oem: string }
  | { kind: "notFound" };

/**
 * Разбор сегмента адреса по номеру детали.
 *
 * ИСПРАВЛЕНИЕ ПРОТИВОРЕЧИЯ В Р3. Постановка требовала одновременно две вещи:
 * «любое иное написание номера („A 463 421 00 98“, „a463-421-0098“) → 301 на
 * нормализованный» и «сегмент, содержащий что-то кроме [A-Za-z0-9], → 404».
 * Оба написания из первого примера как раз содержат пробел и дефис — то есть
 * второе правило отменяло первое, и главный сценарий истории (человек ввёл
 * номер так, как он написан на детали) упирался бы в 404. Правила разведены
 * по моменту применения: до нормализации допускается что угодно, ПОСЛЕ неё
 * остаток обязан быть `[A-Z0-9]`.
 *
 * Порядок именно такой:
 *  1. нормализуем — верхний регистр, только буквы и цифры;
 *  2. пусто → 404 (сегмент был из одной пунктуации);
 *  3. в остатке не только латиница с цифрами → 404. Двойники («А» вместо «A»)
 *     сюда не доходят: `oemKey` переводит их в латиницу, и номер, набранный в
 *     русской раскладке, доводит до страницы редиректом, а не упирается в 404 —
 *     ради этого трафика история и затевалась. Остаётся грубая ошибка вроде
 *     русского слова: у неё публичного адреса нет;
 *  4. написание отличается от канонического → 301 на канонический, иначе у
 *     одной номенклатуры появилось бы сколько угодно живых адресов — та самая
 *     каннибализация, которую вычистила Story 5;
 *  5. иначе это и есть канонический адрес.
 *
 * Сегмент ДЕКОДИРУЕТСЯ здесь. Проверено на живом сервере: Next отдаёт его
 * как есть, в процентной кодировке. Без декодирования «A%20000%20760%2012%2059»
 * (номер, набранный с пробелами) превращался в «A200002076020122059» — каждое
 * «%20» теряло знак процента и добавляло к номеру лишние «20», — и человек
 * уезжал постоянным редиректом на несуществующий адрес. Кириллица же
 * («%D0%90») давала «D090…» и проскакивала мимо проверки на не-латиницу.
 * Ни то, ни другое не видно ни в типах, ни в сборке — только запросом.
 *
 * Декодируем РОВНО ОДИН раз: повторное декодирование склеило бы «%2541» в «AA»
 * вместо «A%41».
 *
 * Про `catch`: он НЕ спасает от битой последовательности вроде «%ZZ». Проверено
 * на живом сервере — такой адрес отдаёт 500 ещё до того, как управление дойдёт
 * сюда, причём одинаково на всех динамических маршрутах проекта («/parts/%ZZ»,
 * «/services/%ZZ», «/blog/%ZZ», «/models/%ZZ»), то есть это поведение
 * платформы, а не этой страницы. Раньше комментарий здесь утверждал обратное.
 * `catch` оставлен как дешёвая защита контракта функции: она вызывается и из
 * тестов, и может быть вызвана из другого места, где вход не проходит через
 * маршрутизатор. Сам 500 на битой кодировке — отдельная задача: боты
 * генерируют такие адреса постоянно, и 500 в статистике хуже 404.
 */
export function resolveOemSegment(raw: string): OemRouteDecision {
  let decoded: string;
  try {
    decoded = decodeURIComponent(raw);
  } catch {
    return { kind: "notFound" };
  }
  const normalized = oemKey(decoded);
  if (normalized === "") return { kind: "notFound" };
  if (!isLatinOem(normalized)) return { kind: "notFound" };
  if (normalized !== decoded) return { kind: "redirect", oem: normalized };
  return { kind: "canonical", oem: normalized };
}
