/**
 * Адрес сайта этой установки — в одном месте.
 *
 * Раньше он вычислялся в тринадцати местах одинаковой строчкой вида
 * `process.env.NEXT_PUBLIC_APP_URL ?? "<домен первого клиента>"`, и фолбэк был
 * не запасным вариантом, а ошибкой: при незаданной переменной платформа
 * считала себя первым клиентом. Второй сервис получил бы чужой домен в карте
 * сайта, в разметке для поисковиков, в письмах и в ссылках на смету.
 *
 * Поэтому правило разное по средам:
 *   в бою      — переменная обязана быть, иначе падаем громко;
 *   в разработке и тестах — `http://localhost:3000`, потому что там домена нет
 *                и требовать его значило бы заставить каждого заводить его руками.
 *
 * Падать в бою лучше, чем подставлять чужой адрес: незаданная переменная — это
 * ошибка настройки, которую надо увидеть при выкате, а не через неделю в
 * поисковой выдаче.
 */

const RAW = process.env.NEXT_PUBLIC_APP_URL?.trim();

/**
 * Сборка — не бой.
 *
 * `next build` идёт в отдельном окружении, куда переменные приложения не
 * попадают: в логе сборки видно, что там нет даже `DATABASE_URL`. При этом
 * `NODE_ENV` там `production`, и требование «в бою переменная обязана быть»
 * роняло сборку — что и случилось на выкате 02.09.
 *
 * Отличать сборку от боя надо по фазе, которую Next выставляет сам
 * (`next/dist/build/index.js`: `process.env.NEXT_PHASE = PHASE_PRODUCTION_BUILD`).
 * Ни один клиентский компонент этот модуль не импортирует, поэтому значение
 * времени сборки никуда не впечатывается: серверные модули читают переменную
 * заново в работающем процессе.
 *
 * Единственное исключение — то, что предрендерится статически. Из потребителей
 * адреса такой ровно один, `robots.txt`, и он переведён на вычисление при
 * запросе.
 */
const IS_BUILD = process.env.NEXT_PHASE === "phase-production-build";

function resolve(): string {
  if (RAW) return RAW.replace(/\/$/, "");
  if (process.env.NODE_ENV === "production" && !IS_BUILD) {
    throw new Error(
      "NEXT_PUBLIC_APP_URL не задана. В бою адрес сайта обязателен: без него " +
        "карта сайта, разметка для поисковиков и ссылки в письмах уйдут не туда.",
    );
  }
  return "http://localhost:3000";
}

/** Адрес сайта без завершающего слэша, например `https://example.com`. */
export const SITE_URL = resolve();

/** Хост без схемы, например `example.com`. */
export const SITE_HOST = new URL(SITE_URL).host;
