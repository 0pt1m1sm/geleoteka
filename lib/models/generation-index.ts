/**
 * Пускать ли страницу поколения в индекс.
 *
 * Правило живёт в ОДНОМ месте, потому что его применяют двое — сама страница
 * (метатегом) и карта сайта. Разъедутся они молча: карта будет заявлять адреса,
 * которые сами себя закрывают, и наоборот.
 *
 * Порог по деталям, а не «хотя бы одна»: страница с единственной привязкой это
 * код кузова, годы и одна ссылка — те же 765 знаков вместе с меню, за которые
 * Яндекс исключил половину сайта как малоценные. Десяток деталей уже даёт
 * оглавление по узлам, то есть содержание, которого нет у соседней страницы.
 *
 * Описание перевешивает количество: текст про слабые места кузова ценен сам по
 * себе, даже если запчастей под него ещё не завели.
 */
export const GENERATION_MIN_PARTS = 10;

export function isGenerationIndexable(input: {
  description: string | null;
  partsCount: number;
}): boolean {
  if (input.description !== null && input.description.trim() !== "") return true;
  return input.partsCount >= GENERATION_MIN_PARTS;
}
