/**
 * Кого из каталога моделей пускать в индекс.
 *
 * Правило живёт в ОДНОМ месте, потому что его применяют двое — сама страница
 * (метатегом) и карта сайта. Разъедутся они молча: карта будет заявлять адреса,
 * которые сами себя закрывают, и наоборот.
 *
 * Порог по деталям, а не «хотя бы одна»: страница с единственной привязкой это
 * код кузова, годы и одна ссылка — те же 765 знаков вместе с меню, за которые
 * Яндекс исключил половину сайта как малоценные. Десяток деталей уже даёт
 * оглавление по узлам, то есть содержание, которого нет у соседней страницы.
 *
 * Описание перевешивает количество: текст про слабые места кузова ценен сам по
 * себе, даже если запчастей под него ещё не завели.
 */
export const GENERATION_MIN_PARTS = 10;

export function isGenerationIndexable(input: {
  description: string | null;
  partsCount: number;
}): boolean {
  if (input.description !== null && input.description.trim() !== "") return true;
  return input.partsCount >= GENERATION_MIN_PARTS;
}

/**
 * Столько знаков описания считаем содержанием, а не подписью.
 *
 * У всех 22 моделей описание сейчас 69–163 знака — одна строчка, одинаковая по
 * форме у каждой. Именно поэтому Яндекс исключил 16 страниц моделей из 35 как
 * маловостребованные. Настоящий абзац начинается примерно отсюда.
 */
export const MODEL_MIN_DESCRIPTION = 400;

/**
 * Пускать ли страницу МОДЕЛИ в индекс.
 *
 * Модель без своего содержания — это шаблон: название, годы поколений и тот же
 * прайс услуг, что у соседа. Такие страницы не ранжируются и тянут оценку
 * домена вниз, а сказать «обслуживаем весь модельный ряд» есть кому: у раздела
 * /models своя страница на 4600 знаков, и она остаётся индексируемой.
 *
 * Сами страницы моделей НЕ прячем: по ним ходят из каталога и подбора. Речь
 * только о том, просить ли их в выдачу. Как только у модели появится настоящее
 * описание или свой набор запчастей, она вернётся в индекс сама.
 */
export function isModelIndexable(input: {
  description: string | null;
  partsCount: number;
}): boolean {
  if ((input.description ?? "").trim().length >= MODEL_MIN_DESCRIPTION) return true;
  return input.partsCount >= GENERATION_MIN_PARTS;
}
