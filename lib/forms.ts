/**
 * Стоит ли галка в отправленной форме.
 *
 * Правило — ПРИСУТСТВИЕ поля, а не его значение: браузер не отправляет снятый
 * чекбокс вовсе. Раньше по коду было написано `formData.get(name) !== "off"` —
 * сравнение со значением, которого форма никогда не шлёт. У снятой галки
 * `get()` возвращает `null`, а `null !== "off"` — истина, то есть галка
 * читалась как поднятая ВСЕГДА и снять её было невозможно в принципе.
 *
 * Проверяем присутствие, а не `=== "on"`, чтобы правило не зависело от
 * атрибута `value`: в наших формах он где-то задан явно, где-то нет, и
 * привязка к «on» сломалась бы на первой же форме с другим значением.
 *
 * Важно: «поля нет в запросе» и «галка снята» для браузера НЕРАЗЛИЧИМЫ.
 * Поэтому вызывать эту функцию можно только там, где форма точно содержит
 * такой чекбокс. Если контрол в форме отсутствует (например, у создания
 * арендной машины), значение задаётся явно на стороне вызова — иначе каждая
 * новая запись молча заводилась бы выключенной.
 */
export function isChecked(formData: FormData, name: string): boolean {
  return formData.get(name) !== null;
}
