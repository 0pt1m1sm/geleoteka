-- Корзина для входящих писем.
--
-- «Удалить» здесь — статус, а не DELETE: ящик остаётся перепиской сервиса, и
-- ошибочно убранное письмо должно возвращаться. Та же причина, по которой
-- удаление клиента не стирает почту.
--
-- Значение только добавляется в enum; существующие строки не читаются и не
-- меняются. В одной транзакции новое значение не используется, поэтому
-- ограничение PostgreSQL на ALTER TYPE ... ADD VALUE здесь не мешает.

ALTER TYPE "InboxMessageStatus" ADD VALUE IF NOT EXISTS 'DELETED';
