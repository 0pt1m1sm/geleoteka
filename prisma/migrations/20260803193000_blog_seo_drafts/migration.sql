## Раздатка: как звучит проблема

Здоровая раздатка не слышна вовсе. Первый симптом износа — вой или гул под нагрузкой на разгоне, пропадающий на сбросе газа: так звучит растянутая цепь. Ездить с ним можно, но недолго — перескочившая или оборванная цепь обездвиживает автомобиль в самый неудобный момент.

Второй сценарий — течи сальников: масляные запотевания на корпусе видно на любом подъёмнике. Объём масла в раздатке небольшой, и «немного подтекает» быстро превращается в «работала насухую».

Что делаем мы: замена цепи с ревизией узла решает вопрос воя; регулярная замена масла (вдвое чаще «вечного» регламента) — лучшая профилактика. Подробнее — на странице [работ по трансмиссии](/services/transmission).

