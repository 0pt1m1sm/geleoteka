-- Варианты товара: новый и б/у на один OEM-номер.
--
-- Блокер, который снимается: Part.article был уникален, поэтому на один
-- OEM-номер нельзя было завести и новую позицию, и б/у экземпляр. Артикул —
-- это номер детали, он по своей природе общий; уникальным становится
-- отдельный торговый идентификатор sku.
--
-- Порядок шагов обязателен: sku добавляется nullable, заполняется, и только
-- потом получает NOT NULL и уникальный индекс. Навесить уникальность до
-- backfill нельзя.
--
-- Backfill дословный (sku := article), а НЕ нормализованный. Причина: на
-- момент этого шага article ещё защищён уникальным индексом, поэтому
-- уникальность sku гарантирована арифметически, независимо от того, какие
-- данные лежат в базе. Нормализация же могла бы схлопнуть два артикула,
-- различающихся только пунктуацией, и уронить миграцию на уникальном
-- индексе — а миграции здесь накатываются автоматически при старте
-- приложения, то есть падение означало бы простой прода.
-- ВАЖНО ДЛЯ ЧИТАТЕЛЯ. Новые товары получают НОРМАЛИЗОВАННЫЙ sku
-- (lib/part-sku.ts), а залитые этой миграцией — дословный. Форматы РАЗНЫЕ, и
-- это не безобидно: искать существующие строки по нормализованному sku
-- нельзя — для артикулов с пунктуацией (на момент миграции 15 из 70 позиций,
-- все ПОДЗАКАЗ-NN и MANN-C29028) ключ не совпадёт с сохранённым, защита от
-- дубля молча выключится, а повторный импорт того же прайса продублирует
-- позиции. Поиск ведём по article + condition И по sku одновременно
-- (OR-запрос) — см. app/actions/parts.ts. Sku остаётся непрозрачным
-- идентификатором; варианты одной детали группируются по referenceId.

-- CreateEnum
CREATE TYPE "PartCondition" AS ENUM ('NEW', 'USED', 'REFURBISHED');

-- AlterTable: новые колонки
ALTER TABLE "Part" ADD COLUMN "sku" TEXT;
ALTER TABLE "Part" ADD COLUMN "condition" "PartCondition" NOT NULL DEFAULT 'NEW';
ALTER TABLE "Part" ADD COLUMN "conditionNote" VARCHAR(1000);
ALTER TABLE "Part" ADD COLUMN "originNote" VARCHAR(500);

-- Backfill: существующие товары — новые, sku равен артикулу
UPDATE "Part" SET "sku" = "article" WHERE "sku" IS NULL;

-- Уникальность переезжает с article на sku
ALTER TABLE "Part" ALTER COLUMN "sku" SET NOT NULL;
CREATE UNIQUE INDEX "Part_sku_key" ON "Part"("sku");

-- Артикул больше не уникален. Обычный индекс Part_article_idx уже существует
-- и сохраняется — поиск по номеру детали не деградирует.
DROP INDEX IF EXISTS "Part_article_key";

-- Индекса по condition сознательно НЕТ: колонка из трёх значений, где после
-- backfill 100% строк — NEW. Планировщик его не возьмёт, а поддерживать при
-- каждой записи пришлось бы. Когда б/у станет много, нужен будет композит
-- (condition, isActive) под конкретный запрос витрины — тогда и заводить.

-- Инвариант «один НОВЫЙ товар на артикул» теперь держит база, а не внимательность
-- трёх вызывающих. До этой миграции его обеспечивал Part_article_key; мы его
-- сняли, чтобы у детали могли сосуществовать новый товар и б/у экземпляры, —
-- но для НОВЫХ ограничение должно остаться прежним.
--
-- Проверено мутацией на ревью: без этого индекса откат OR-запроса обратно на
-- один ключ проходит весь гейт зелёным, и в каталоге молча появляются дубли.
-- С индексом тот же откат превращается в P2002, который уже перехвачен и
-- показывается как «Запчасть с таким артикулом уже существует».
--
-- Частичный (WHERE condition = 'NEW'), поэтому б/у экземпляры с тем же
-- артикулом ему не мешают — ради них всё и затевалось.
-- Prisma не умеет частичные уникальные индексы в схеме, поэтому сырым SQL —
-- как Part_photos_gin_idx в 20260505123839_add_uploaded_image.
-- Применимо: на момент миграции article ещё уникален глобально, значит двух
-- строк NEW с одним артикулом существовать не может по построению.
CREATE UNIQUE INDEX IF NOT EXISTS "Part_article_new_uq" ON "Part"("article") WHERE "condition" = 'NEW';
