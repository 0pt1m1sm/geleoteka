-- Страна, валюта, локаль и часовой пояс арендатора.
--
-- Продукт универсальный: первый сервис оказался в России, но второй может быть
-- где угодно. Сегодня это чистое расширение — единственная строка получает
-- значения по умолчанию, ровно те, по которым код работает сейчас, и поведение
-- не меняется ни на бит. Когда в базе появится второй арендатор из другой
-- страны, той же миграции уже не будет: валюту существующих строк придётся
-- откуда-то брать, а взять её будет неоткуда.
--
-- Значения по умолчанию остаются на колонках намеренно. Арендатор заводится не
-- только кодом (миграция, seed, ручная вставка при разборе), и колонка без
-- умолчания превратила бы каждую такую вставку в обязательный список из
-- четырёх полей. Умолчание «как у первого клиента» здесь честнее: оно
-- воспроизводит то, что и так зашито в коде, а не выдаёт себя за выбор.

ALTER TABLE "Tenant"
  ADD COLUMN IF NOT EXISTS "country"  TEXT NOT NULL DEFAULT 'RU',
  ADD COLUMN IF NOT EXISTS "currency" TEXT NOT NULL DEFAULT 'RUB',
  ADD COLUMN IF NOT EXISTS "locale"   TEXT NOT NULL DEFAULT 'ru-RU',
  ADD COLUMN IF NOT EXISTS "timeZone" TEXT NOT NULL DEFAULT 'Europe/Moscow';
