### Мехатроник
На 722.9 и особенно на 9G-Tronic гидроблок и электронный блок управления объединены в единый узел — мехатроник. Здесь к гидравлике добавляется электроника: датчики, соленоиды с электронным управлением. Если мехатроник начинает сбоить, коробка может «путаться» в передачах, дёргаться или уходить в аварийный режим без явной механической причины.

