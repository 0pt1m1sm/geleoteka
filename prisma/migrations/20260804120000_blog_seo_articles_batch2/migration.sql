## Где искать очаги коррозии

### Рама и лонжероны
Самое уязвимое место — сварные швы и внутренние полости лонжеронов, где влага скапливается и не высыхает годами. Особенно страдают зоны у креплений мостов и домкратные точки: снаружи может быть всё чисто, а внутри уже идёт процесс.

### Кронштейны кузова
Резинометаллические кронштейны, на которых кузов сидит на раме, ржавеют изнутри и со временем «закисают» — тогда при снятии кузова (а такое бывает нужно при серьёзном ремонте) их приходится буквально срезать.

### Двери и пороги
Пороги Гелендвагена — коробчатая конструкция с внутренними полостями, куда грязь набивается через дренажные отверстия. Если дренаж забит, вода стоит внутри порога месяцами. Двери ржавеют по нижней кромке и в районе стеклоподъёмников, где скапливается конденсат.

