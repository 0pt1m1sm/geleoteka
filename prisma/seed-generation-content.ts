async function main() {
  const model = await db.vehicleModel.findUnique({
    where: { slug: "g-class" },
    select: { id: true },
  });
  if (!model) throw new Error("Модель g-class не найдена");

  for (const [code, content] of Object.entries(CONTENT)) {
    const res = await db.vehicleGeneration.updateMany({
      where: { modelId: model.id, code },
      data: { description: content.description, commonIssues: content.commonIssues },
    });
    console.log(`${code}: обновлено строк ${res.count}`);
  }

  const filled = await db.vehicleGeneration.count({
    where: { modelId: model.id, description: { not: null } },
  });
  console.log(`итого поколений с описанием: ${filled}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => db.$disconnect());
