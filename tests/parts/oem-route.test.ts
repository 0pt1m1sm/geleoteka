import { describe, expect, it } from "vitest";
import { resolveOemSegment } from "@/lib/parts/oem-route";

/**
 * Правило адреса страницы по номеру детали.
 *
 * Смысл истории — перестать терять горячий трафик по номеру. Значит главный
 * проверяемый случай не «канонический адрес открывается», а «номер, записанный
 * так, как он напечатан на детали, доводит до страницы».
 */
describe("resolveOemSegment", () => {
  it("канонический номер открывается как есть", () => {
    expect(resolveOemSegment("A4634210098")).toEqual({ kind: "canonical", oem: "A4634210098" });
  });

  it("номер с пробелами доводит до страницы, а НЕ в 404", () => {
    // Так он напечатан на детали и так его вводят. Формулировка постановки
    // требовала на это 404 — противоречие исправлено в реализации.
    expect(resolveOemSegment("A 463 421 00 98")).toEqual({
      kind: "redirect",
      oem: "A4634210098",
    });
  });

  it("нижний регистр и дефисы — тоже доводят", () => {
    expect(resolveOemSegment("a463-421-0098")).toEqual({
      kind: "redirect",
      oem: "A4634210098",
    });
  });

  it("точки и слэши в номере не мешают", () => {
    expect(resolveOemSegment("A463.421.00.98")).toEqual({
      kind: "redirect",
      oem: "A4634210098",
    });
  });

  it("одна пунктуация — 404, а не редирект в пустоту", () => {
    // Без этой ветки получился бы редирект на /parts/oem/ — адрес, которого
    // не существует, то есть бесконечная петля или 500 вместо честного 404.
    for (const raw of ["---", "   ", ".", ""]) {
      expect(resolveOemSegment(raw), raw).toEqual({ kind: "notFound" });
    }
  });

  it("кириллица — 404: нормализация её пропускает, но такого номера не бывает", () => {
    // normalizeOem сохраняет А-ЯЁ, так что без явной проверки сюда пришёл бы
    // «канонический» адрес с не-ASCII сегментом. В справочнике таких нет ни
    // одной из 487 позиций — это ошибка ввода, а не номер.
    expect(resolveOemSegment("А4634210098")).toEqual({ kind: "notFound" });
    expect(resolveOemSegment("ДЕТАЛЬ")).toEqual({ kind: "notFound" });
  });

  it("ПРОЦЕНТНАЯ КОДИРОВКА разбирается — найдено проверкой на живом сервере", () => {
    // Next отдаёт сегмент как есть, не декодируя. Без декодирования каждое
    // «%20» теряло знак процента и дописывало к номеру «20»: человек, набравший
    // номер с пробелами, уезжал постоянным редиректом на несуществующий адрес.
    expect(resolveOemSegment("A%20000%20760%2012%2059")).toEqual({
      kind: "redirect",
      oem: "A0007601259",
    });
  });

  it("кириллица в кодировке ловится так же, как в открытом виде", () => {
    // «%D0%90» — это «А». Без декодирования получалось «D090…»: проверка на
    // не-латиницу не срабатывала, и рождался канонический адрес из мусора.
    expect(resolveOemSegment("%D0%904634210098")).toEqual({ kind: "notFound" });
  });

  it("битая последовательность — 404, а не падение страницы", () => {
    expect(resolveOemSegment("%ZZ")).toEqual({ kind: "notFound" });
    expect(resolveOemSegment("%")).toEqual({ kind: "notFound" });
  });

  it("уже нормализованное НЕ уходит в редирект — иначе петля", () => {
    // Цель редиректа обязана быть неподвижной точкой правила.
    const first = resolveOemSegment("a 463 421 00 98");
    expect(first.kind).toBe("redirect");
    if (first.kind !== "redirect") return;
    expect(resolveOemSegment(first.oem)).toEqual({ kind: "canonical", oem: first.oem });
  });
});
