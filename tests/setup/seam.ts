import { vi } from "vitest";

/**
 * Общая подмена шва изоляции для всех тестов.
 *
 * Модули приложения берут клиент базы из `tenantDb()`, а тесты подменяют сам
 * клиент (`@/lib/db`) своей заглушкой. Без этой подмены шов пошёл бы за
 * арендатором в настоящую базу — и тест падал бы по причине, к его предмету
 * отношения не имеющей.
 *
 * Подмена сделана один раз здесь, а не в каждом тесте: правка сорока файлов
 * ради одной и той же строчки — это не работа, а её имитация. Предметом теста
 * остаётся сам модуль; изоляцию проверяют отдельные тесты в tests/tenant,
 * которые обращаются к шву напрямую и этой подмены не касаются.
 */
vi.mock("server-only", () => ({}));

vi.mock("@/lib/tenant/scoped-db", async () => {
  const { db } = await import("@/lib/db");
  return {
    tenantDb: async () => db,
    invalidateScopedDbCache: () => {},
  };
});
